import { readFile, writeFile } from 'node:fs/promises';

const source = new URL('../docs/design-tokens.json', import.meta.url);
const target = new URL('../src/shared/styles/tokens.css', import.meta.url);
const { $meta, ...tokens } = JSON.parse(await readFile(source, 'utf8'));
const variables = new Map();

function collect(group, prefix = '') {
  for (const [name, item] of Object.entries(group)) {
    const path = prefix ? prefix + '.' + name : name;
    if ('$value' in item) variables.set(path, item);
    else collect(item, path);
  }
}

function cssName(path) {
  return (
    '--dp-' + path.replace(/[A-Z]/g, (letter) => '-' + letter.toLowerCase()).replaceAll('.', '-')
  );
}

function render(path, chain = []) {
  const token = variables.get(path);
  if (!token || chain.includes(path)) {
    throw new Error('Invalid design token reference: ' + [...chain, path].join(' → '));
  }
  const alias = typeof token.$value === 'string' && /^\{(.+)\}$/.exec(token.$value);
  if (!alias) return token.$value;

  const reference = alias[1];
  render(reference, [...chain, path]);
  if (variables.get(reference).$type !== token.$type) {
    throw new Error('Design token type mismatch: ' + path + ' → ' + reference);
  }
  return 'var(' + cssName(reference) + ')';
}

function responsive(breakpoint, declarations) {
  return [
    '@media (min-width: ' + render('breakpoint.' + breakpoint) + ') {',
    '  :root {',
    ...Object.entries(declarations).map(
      ([role, path]) => '    --dp-' + role + ': var(' + cssName(path) + ');',
    ),
    '  }',
    '}',
  ];
}

collect(tokens);
const output = [
  '/* Generated by npm run tokens:generate from docs/design-tokens.json (' + $meta.status + '). */',
  ':root {',
  ...Array.from(variables.keys(), (path) => '  ' + cssName(path) + ': ' + render(path) + ';'),
  '  --dp-page-gutter: var(--dp-layout-gutter-compact);',
  '  --dp-form-font-size: var(--dp-typography-size-control-mobile);',
  '  --dp-form-line-height: var(--dp-typography-line-height-control-mobile);',
  '  --dp-title-size: var(--dp-typography-size-page-compact);',
  '  --dp-title-height: var(--dp-typography-line-height-page-compact);',
  '}',
  '',
  ...responsive('medium', {
    'page-gutter': 'layout.gutterMedium',
    'form-font-size': 'typography.size.compact',
    'form-line-height': 'typography.lineHeight.compact',
    'title-size': 'typography.size.page',
    'title-height': 'typography.lineHeight.page',
  }),
  '',
  ...responsive('large', { 'page-gutter': 'layout.gutterWide' }),
  '',
].join('\n');

if ((await readFile(target, 'utf8').catch(() => '')) !== output) await writeFile(target, output);
